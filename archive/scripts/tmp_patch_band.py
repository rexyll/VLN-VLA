"""tmp_patch_band.py —— P28: 深度取样行带按"仰角"重算

原实现:
    r0, r1 = int(h*0.10), int(h*0.45)
注释写"该带射线均在水平线以上, 排除地面与自身底盘自遮挡"。
但按 VFOV=83.58° 换算, 这两行对应的仰角是 **+33.4° ~ +4.2°**:
  行24  -> (120-24)/240*83.58 = +33.4°
  行108 -> (120-108)/240*83.58 = +4.2°   (仅是带子的底边)

后果: 一条仰角 e 的射线在距离 d 处的高度是 0.23+d*tan(e)。0.8m 高的立
柱在 3m 处顶只到 10.6° 仰角、4m 处只到 8°, 于是**只有带子最底下几行能
看到它**, 有效像素远低于 5% 分位数所需的 5%, 分位数直接落到后面的墙。
实测标定(robot(-1.60,-0.90) yaw0): right 相机中心扇区实测 5.10m, 而
ob6 的表面真值只有 2.81m —— 漏检 2.3m。

改为按仰角取带:
    下沿 +1.5°  -> 地面(相机高 0.23m)落在 8.8m, 落在 5% 分位数之外,
                    既排除地面回波, 又能看见远处矮障碍
    上沿 +18.0° -> 只看"可能有障碍"的高度, 天空/远处高墙交给别的扇区
"""
import shutil
import sys

P = '/home/earl/workspace/VLA/vla_ws/src/vla_follow/vla_follow/depth_percept.py'
shutil.copy(P, P + '.bak_band')
s = open(P, encoding='utf-8').read()

OLD = """            # 上带视场(行10%~45%): 该带射线均在水平线以上,
            # 排除地面与机器人自身底盘的自遮挡
            r0, r1 = int(h * 0.10), int(h * 0.45)"""

NEW = """            # P28: 按"仰角"取带, 不再用拍脑袋的行百分比。
            # 原 10%~45% 行 = 仰角 +33.4°~+4.2°, 底边太高: 0.8m 立柱在
            # 4m 处只到 8° 仰角, 几乎整个落在带外, 5% 分位数落到身后的墙
            # (实测 right 中心扇区 5.10m / 真值 2.81m)。
            # 下沿 +1.5°: 地面(相机高约 0.23m)回波在 8.8m, 不参与 5% 分位;
            # 上沿 +18°: 覆盖近处障碍全高, 又不把天空算进来。
            # 行号 = h/2 - elev/VFOV*h,  VFOV = 83.58°
            r0 = int(h * (0.5 - 18.0 / 83.58))      # 上沿 +18.0°
            r1 = int(h * (0.5 - 1.5 / 83.58)) + 1   # 下沿 +1.5°
            r0, r1 = max(0, r0), min(h, r1)"""

if s.count(OLD) != 1:
    print('!! 行带锚点异常')
    sys.exit(1)
s = s.replace(OLD, NEW, 1)

open(P, 'w', encoding='utf-8').write(s)
print('PATCH_OK')
print('  含 r0 新算法:', s.count('r0 = int(h * (0.5 - 18.0 / 83.58))'))
